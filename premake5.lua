    platforms { 'x64' }
    defaultplatform 'x64'
    location 'build/%{_ACTION}'

    if _ACTION == 'compilecommands' then
        os.mkdir('build/compilecommands')
    end

    scoped.filter({
        'action:not vs*'
    }, function()
         toolset 'clang'
    end)

    scoped.filter({
        'action:vs*'
    }, function()
        toolset 'v143'
        usestandardpreprocessor 'On'
        disablewarnings { '4251' }
    end)

    scoped.filter({
        'action:vs2026'
    }, function()
        toolset 'v145'
    end)

    scoped.filter({
        'configurations:Debug'
    }, function()
        defines { '_DEBUG' }

